def write_csv(path, header, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)

def to(fmt, src, outdir, infilter=None):
    cmd = ["soffice", "--headless", "--norestore", "-env:UserInstallation=file:///tmp/claude-1000/lo-people-profile"]
    if infilter:
        cmd += [f"--infilter={infilter}"]
    cmd += ["--convert-to", fmt, "--outdir", outdir, src]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, env={**os.environ, "SAL_DISABLE_CUPS": "1"})

def xlsx(name, header, rows, outdir):
    tmp = os.path.join(HERE, "_build")
    os.makedirs(tmp, exist_ok=True)
    p = os.path.join(tmp, name + ".csv")
    write_csv(p, header, rows)
    to("xlsx", p, outdir, "CSV:44,34,76,1")

