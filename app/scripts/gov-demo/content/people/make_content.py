def html_doc(title, body):
    return f"""<!doctype html><html dir="rtl" lang="ar"><head><meta charset="utf-8"><title>{title}</title><style>{CSS}</style></head>
<body dir="rtl"><p class="hdr">المملكة العربية السعودية — {AGENCY}<br/>(جهة وهمية لأغراض العرض)</p>{body}</body></html>"""

def word(name, title, body, outdir, pdf=False):
    tmp = os.path.join(HERE, "_build")
    os.makedirs(tmp, exist_ok=True)
    p = os.path.join(tmp, name + ".html")
    with open(p, "w", encoding="utf-8") as f:
        f.write(html_doc(title, body))
    to("docx:MS Word 2007 XML", p, tmp if pdf else outdir)
    if pdf:
        to("pdf", os.path.join(tmp, name + ".docx"), outdir)

def table(header, rows):
    h = "".join(f"<th>{x}</th>" for x in header)
    b = "".join("<tr>" + "".join(f"<td>{x}</td>" for x in r) + "</tr>" for r in rows)
    return f"<table><tr>{h}</tr>{b}</table>"

