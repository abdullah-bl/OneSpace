def convert(html_name, html, fmt, final_name, dest=OUT):
    src = os.path.join(WORK, html_name)
    with open(src, "w", encoding="utf-8") as f:
        f.write(html)
    subprocess.run(["soffice", f"-env:UserInstallation={PROFILE}", "--headless", "--convert-to", fmt, "--outdir", WORK, src], check=True, capture_output=True)
    produced = os.path.join(WORK, os.path.splitext(html_name)[0] + "." + fmt.split(":")[0])
    os.replace(produced, os.path.join(dest, final_name))

def to_xlsx(csv_name, rows, final_name, dest=OUT):
    src = os.path.join(WORK, csv_name)
    with open(src, "w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerows(rows)
    subprocess.run(["soffice", f"-env:UserInstallation={PROFILE}", "--headless", "--infilter=CSV:44,34,76,1", "--convert-to", "xlsx", "--outdir", WORK, src], check=True, capture_output=True)
    os.replace(os.path.join(WORK, os.path.splitext(csv_name)[0] + ".xlsx"), os.path.join(dest, final_name))

def table(head, rows):
    h = "".join(f"<th>{x}</th>" for x in head)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><tr>{h}</tr>{b}</table>"

